import { isDbHealthy } from '../config/db.js';
import { isRedisHealthy, getRedisClient } from '../config/redis.js';
import { getQueueMetrics } from '../queues/lead.queue.js';
import { getErrorLogs, clearErrorLogs, recordError } from '../utils/errorTracker.js';
import mongoose from 'mongoose';

export function getHealth(req, res) {
  res.status(200).json({
    status: 'OK',
    timestamp: new Date().toISOString(),
    uptime: process.uptime()
  });
}

export async function getReadiness(req, res) {
  const dbOk = isDbHealthy();
  const redisOk = await isRedisHealthy();

  const isReady = dbOk && redisOk;
  const status = isReady ? 200 : 503;

  res.status(status).json({
    status: isReady ? 'READY' : 'NOT_READY',
    checks: {
      database: dbOk ? 'UP' : 'DOWN',
      redis: redisOk ? 'UP' : 'DOWN'
    },
    timestamp: new Date().toISOString()
  });
}

/**
 * Detailed telemetry, infrastructure stats, and developer error logs
 */
export async function getSystemHealthMetrics(req, res, next) {
  try {
    const [queueMetrics, redisUp] = await Promise.all([
      getQueueMetrics(),
      isRedisHealthy()
    ]);

    const redis = getRedisClient();
    let redisInfo = {};
    if (redisUp) {
      try {
        const rawInfo = await redis.info('memory');
        const memoryMatch = rawInfo.match(/used_memory_human:(.*)/);
        if (memoryMatch) {
          redisInfo.usedMemory = memoryMatch[1].trim();
        }

        const clientsMatch = (await redis.info('clients')).match(/connected_clients:(.*)/);
        if (clientsMatch) {
          redisInfo.connectedClients = parseInt(clientsMatch[1].trim(), 10);
        }

        const totalKeys = await redis.dbsize();
        redisInfo.totalKeys = totalKeys;
      } catch {}
    }

    const dbStats = {
      status: isDbHealthy() ? 'UP' : 'DOWN',
      readyState: mongoose.connection.readyState,
      dbName: mongoose.connection.name,
      host: mongoose.connection.host,
      modelsRegistered: Object.keys(mongoose.models).length,
      maxPoolSize: parseInt(process.env.MONGODB_MAX_POOL_SIZE || '50', 10),
      minPoolSize: parseInt(process.env.MONGODB_MIN_POOL_SIZE || '10', 10)
    };

    const memoryUsage = process.memoryUsage();
    const errors = getErrorLogs();

    return res.status(200).json({
      success: true,
      data: {
        system: {
          uptimeSeconds: Math.floor(process.uptime()),
          nodeVersion: process.version,
          platform: process.platform,
          arch: process.arch,
          pid: process.pid,
          environment: process.env.NODE_ENV || 'development',
          workerConcurrency: parseInt(process.env.LEAD_WORKER_CONCURRENCY || '20', 10),
          inProcessWorkerActive: process.env.START_IN_PROCESS_WORKER !== 'false',
          rateLimitSkipped: process.env.SKIP_RATE_LIMIT === 'true',
          memoryUsage: {
            heapUsedMB: Math.round(memoryUsage.heapUsed / 1024 / 1024),
            heapTotalMB: Math.round(memoryUsage.heapTotal / 1024 / 1024),
            rssMB: Math.round(memoryUsage.rss / 1024 / 1024),
            externalMB: Math.round(memoryUsage.external / 1024 / 1024)
          },
          cpuUsage: process.cpuUsage()
        },
        database: dbStats,
        redis: {
          status: redisUp ? 'UP' : 'DOWN',
          url: (process.env.REDIS_URL || 'redis://127.0.0.1:6379').replace(/:[^:@]*@/, ':***@'),
          ...redisInfo
        },
        queue: queueMetrics,
        errors: {
          totalCount: errors.length,
          recent: errors
        }
      },
      requestId: req.id
    });
  } catch (error) {
    next(error);
  }
}

/**
 * Return only recorded errors for developer polling
 */
export function getSystemErrors(req, res) {
  const errors = getErrorLogs();
  return res.status(200).json({
    success: true,
    data: {
      totalCount: errors.length,
      errors
    },
    requestId: req.id
  });
}

/**
 * Clear developer error logs
 */
export function clearSystemErrorsHandler(req, res) {
  clearErrorLogs();
  return res.status(200).json({
    success: true,
    message: 'Error debug buffer has been cleared.',
    requestId: req.id
  });
}

/**
 * Trigger a simulated debug test exception
 */
export function triggerTestErrorHandler(req, res, next) {
  const error = new Error(`Simulated Diagnostic Test Exception generated by Developer @${req.user?.username || 'developer'} at ${new Date().toISOString()}`);
  error.code = 'SIMULATED_DEBUG_EXCEPTION';
  error.statusCode = 500;
  next(error);
}
